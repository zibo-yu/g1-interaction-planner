"""Build KiMoDo Python constraints from MPC targets and generate a SOMA clip.

The direct constraint-object route is deliberate: native constraints.json encodes a
fully FK-consistent skeleton, which task-space MPC alone cannot supply. This
bridge never mislabels Cartesian targets as native KiMoDo JSON.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

import numpy as np
from scipy.spatial.transform import Rotation


def _single_clip(a, name, expected_tail):
    arr = np.asarray(a)
    expected_ndim = (4 if name == 'local_rot_mats' else 2)
    if arr.ndim == expected_ndim + 1:
        if arr.shape[0] != 1:
            raise ValueError(f"{name}: only single-clip reference supported, got {arr.shape}")
        arr = arr[0]
    if arr.ndim != expected_ndim or tuple(arr.shape[-len(expected_tail):]) != expected_tail:
        raise ValueError(f"{name}: unexpected array shape {arr.shape}")
    return arr


def reference_pose(reference_path, skeleton, frame_index=0):
    """Load KiMoDo NPZ local rotations, convert 77→30 if necessary, run SAME skeleton FK.

    This avoids relying on joint ordering in external ELF3 URDFs or cached
    posed_joints arrays from a different skeleton variant.
    """
    import torch
    from kimodo.skeleton import SOMASkeleton30, SOMASkeleton77
    with np.load(reference_path, allow_pickle=False) as data:
        if not {'local_rot_mats', 'root_positions'} <= set(data.files):
            raise ValueError("Reference must be a KiMoDo NPZ with local_rot_mats and root_positions")
        rots = _single_clip(data['local_rot_mats'], 'local_rot_mats', (3, 3))
        roots = _single_clip(data['root_positions'], 'root_positions', (3,))
    if len(rots) != len(roots):
        raise ValueError("Reference rotations/root lengths disagree")
    index = frame_index if frame_index >= 0 else len(roots) + frame_index
    if not (0 <= index < len(roots)):
        raise ValueError(f"Reference frame index {frame_index} outside 0..{len(roots)-1}")
    device = skeleton.neutral_joints.device
    local = torch.as_tensor(rots[index:index+1], dtype=torch.float32, device=device)
    if local.shape[1] != skeleton.nbjoints:
        if local.shape[1] == 77 and isinstance(skeleton, SOMASkeleton30):
            local = skeleton.from_SOMASkeleton77(local)
        elif local.shape[1] == 30 and isinstance(skeleton, SOMASkeleton77):
            local = SOMASkeleton30().to(device).to_SOMASkeleton77(local)
        else:
            raise ValueError(f"Cannot adapt {local.shape[1]} joints to {skeleton.nbjoints}")
    root = torch.as_tensor(roots[index:index+1], dtype=torch.float32, device=device)
    with torch.no_grad():
        rr, pp, _ = skeleton.fk(local, root)
    return pp[0].cpu().numpy(), rr[0].cpu().numpy(), root[0].cpu().numpy()


def _validate_target_file(path):
    obj = json.loads(Path(path).read_text(encoding='utf8'))
    if obj.get('schema_version') != 'soma_task_targets/v1':
        raise ValueError('Expected soma_task_targets/v1 generated by targets.py')
    t = int(obj['num_frames'])
    inds = [int(i) for i in obj['right_hand_frame_indices']]
    if len(set(inds)) != len(inds) or any(i < 0 or i >= t for i in inds):
        raise ValueError('Invalid right-hand frame indices')
    roots = [int(i) for i in obj.get('root_frame_indices', range(t))]
    if not roots or len(set(roots)) != len(roots) or any(i < 0 or i >= t for i in roots):
        raise ValueError('Invalid root frame indices')
    split = obj.get('phase_split_frame')
    if split is not None and (not isinstance(split, int) or not 0 < split < t):
        raise ValueError('Invalid phase_split_frame')
    for field in ('pelvis_position_m', 'pelvis_orientation_xyzw', 'right_wrist_position_m',
                  'right_wrist_orientation_xyzw', 'right_hand_tip_position_m'):
        a = np.asarray(obj['trajectories'][field], dtype=float)
        if a.shape != (t, 4 if field.endswith('xyzw') else 3) or not np.isfinite(a).all():
            raise ValueError('Invalid trajectory field '+field)
    return obj


def create_constraints(targets, skeleton, reference_pos, reference_rot, reference_root,
                       reference_yaw_rad=0.0, tip_policy='calibrated',
                       max_tip_discrepancy_m=None):
    """Create in-memory root2d + right-hand targets and diagnostic tensors.

    Root position and hand positions are shifted consistently to SOMA's nominal
    reference root height, avoiding ELF3-proxy pelvis=0.64m sinking SOMA feet.
    The reference's hand-tip local vector calibrates SOMA's MiddleEnd point.
    """
    import torch
    from kimodo.constraints import RightHandConstraintSet, Root2DConstraintSet
    if tip_policy not in ('calibrated', 'planned'):
        raise ValueError('tip_policy must be calibrated or planned')
    inds = np.asarray(targets['right_hand_frame_indices'], dtype=np.int64)
    traj = {k: np.asarray(v, dtype=np.float64) for k,v in targets['trajectories'].items()}
    n = int(targets['num_frames'])
    names = skeleton.bone_index
    root_idx = skeleton.root_idx
    wi = names['RightHand']
    ti = names['RightHandMiddleEnd']
    plan_pelvis = traj['pelvis_position_m']
    plan_wrist = traj['right_wrist_position_m']
    plan_tip = traj['right_hand_tip_position_m']
    body_r = Rotation.from_quat(traj['pelvis_orientation_xyzw'])
    wrist_r = Rotation.from_quat(traj['right_wrist_orientation_xyzw'])
    R_ref_heading_inv = Rotation.from_euler('y', -reference_yaw_rad)
    align = body_r * R_ref_heading_inv
    # Source root height difference is applied uniformly to the whole planned clip.
    vertical_shift = float(reference_root[1] - plan_pelvis[0,1])
    dy = np.array([0.0, vertical_shift, 0.0])
    soma_root = plan_pelvis + dy
    rel_ref_joint_pos = reference_pos - reference_pos[root_idx]
    target_positions = np.empty((len(inds), skeleton.nbjoints, 3))
    target_rotations = np.empty((len(inds), skeleton.nbjoints, 3, 3))
    nominal_tip_local = reference_rot[wi].T @ (reference_pos[ti] - reference_pos[wi])
    tip_gaps = []
    for a, i in enumerate(inds):
        A = align[i].as_matrix()
        target_positions[a] = soma_root[i] + rel_ref_joint_pos @ A.T
        target_rotations[a] = A @ reference_rot
        target_positions[a,wi] = plan_wrist[i] + dy
        # Constant planner wrist quaternion is a schematic orientation; interpret its
        # CHANGES relative to initial input, applied to the reference SOMA wrist.
        R_w = (wrist_r[i] * wrist_r[0].inv()).as_matrix() @ (A @ reference_rot[wi])
        target_rotations[a,wi] = R_w
        derived_tip = target_positions[a,wi] + R_w @ nominal_tip_local
        tip_gap = float(np.linalg.norm(derived_tip - (plan_tip[i] + dy)))
        tip_gaps.append(tip_gap)
        target_positions[a,ti] = derived_tip if tip_policy == 'calibrated' else plan_tip[i] + dy
    if max_tip_discrepancy_m is not None and tip_gaps and max(tip_gaps) > max_tip_discrepancy_m:
        raise ValueError(f"Plan tip does not match SOMA geometry: max gap {max(tip_gaps):.3f}m; "
                         'use calibrated tip or adjust target geometry')
    hand_set = set(inds.tolist())
    root_waypoints = [int(i) for i in targets.get('root_frame_indices', range(n))]
    root_ids = np.asarray([i for i in root_waypoints if i not in hand_set], dtype=np.int64)
    device = skeleton.neutral_joints.device
    constraints = []
    if len(inds):
        hand = RightHandConstraintSet(
            skeleton,
            torch.as_tensor(inds.copy(), dtype=torch.long),
            torch.as_tensor(target_positions, dtype=torch.float32, device=device),
            torch.as_tensor(target_rotations, dtype=torch.float32, device=device),
            torch.as_tensor(soma_root[inds][:,[0,2]].copy(), dtype=torch.float32, device=device),
        )
        constraints.append(hand)
    # Avoid duplicate root constraints on exactly the same frames.
    if len(root_ids):
        constraints.insert(0, Root2DConstraintSet(
            skeleton,
            torch.as_tensor(root_ids.copy(),dtype=torch.long),
            torch.as_tensor(soma_root[root_ids][:,[0,2]].copy(),dtype=torch.float32,device=device)))
    diagnostics = {
        'frame_indices': inds.tolist(),
        'soma_root_positions_m': soma_root.tolist(),
        'right_wrist_targets_m': (plan_wrist + dy).tolist(),
        'right_tip_targets_planned_m': (plan_tip + dy).tolist(),
        'right_tip_targets_applied_m': target_positions[:,ti].tolist(),
        'right_wrist_targets_applied_m': target_positions[:,wi].tolist(),
        'tip_local_m_from_soma_reference': nominal_tip_local.tolist(),
        'tip_discrepancy_m_at_keyframes': tip_gaps,
        'max_tip_discrepancy_m': max(tip_gaps) if tip_gaps else None,
        'soma_root_height_shift_m': vertical_shift,
        'root_dense_indices_without_hand_overlap': root_ids.tolist(),
        'tip_policy': tip_policy,
        'warning': ('Direct global-hand constraints do not certify skeletal IK feasibility; '
                    'native JSON round-tripping would recompute joint positions via FK.'),
    }
    return constraints, diagnostics


def _run_generation(model, constraints, targets, prompt, diffusion_steps=100, seed=7,
                    walk_prompt=None, reach_prompt=None, num_transition_frames=8,
                    single_prompt=False):
    from kimodo.tools import seed_everything
    seed_everything(seed)
    # Native KiMoDo multi-prompt segmentation; constraints use global frame indices.
    split = targets.get('phase_split_frame')
    if split is not None and not single_prompt:
        prompts = [walk_prompt or 'A person walks forward, gradually slows down and stops.',
                   reach_prompt or 'A person slows down, stops walking, and extends their right hand for a handshake.']
        lengths = [int(split), int(targets['num_frames']) - int(split)]
        if min(lengths) <= num_transition_frames:
            raise ValueError('Each segment must exceed the transition frame count. '
                             'Adjust the gain threshold, duration, or --num-transition-frames.')
    else:
        prompts = [walk_prompt or 'A person walks forward, gradually slows down and stops.'
                   if not targets['right_hand_frame_indices'] else prompt]
        lengths = [int(targets['num_frames'])]
    print(f'KiMoDo prompts: {list(zip(prompts,lengths))}',flush=True)
    output = model(prompts, lengths, constraint_lst=constraints,
                   num_denoising_steps=diffusion_steps, num_samples=1,
                   multi_prompt=True, num_transition_frames=num_transition_frames,
                   post_processing=True, return_numpy=True)
    return output


def _save_generation(output, model, outstem):
    import torch
    from kimodo.exports.motion_io import save_kimodo_npz
    from kimodo.exports.bvh import save_motion_bvh
    from kimodo.skeleton import SOMASkeleton30, global_rots_to_local_rots
    dst = Path(outstem)
    dst.parent.mkdir(parents=True, exist_ok=True)
    n = output['posed_joints'].shape[0]
    if n != 1:
        raise ValueError(f'Expected exactly 1 generated clip, got {n}')
    sample = {k: (v[0] if hasattr(v,'shape') and getattr(v,'ndim',0)>0 and v.shape[0]==n else v)
              for k,v in output.items()}
    save_kimodo_npz(str(dst)+'.npz', sample)
    skeleton = model.skeleton
    if isinstance(skeleton, SOMASkeleton30):
        skeleton = skeleton.somaskel77
    device = skeleton.neutral_joints.device
    gp = torch.as_tensor(sample['posed_joints'], dtype=torch.float32, device=device)
    gr = torch.as_tensor(sample['global_rot_mats'], dtype=torch.float32, device=device)
    if gp.shape[1] != skeleton.nbjoints:
        raise ValueError('Generated joint count incompatible with export skeleton')
    local = global_rots_to_local_rots(gr, skeleton)
    root = gp[:,skeleton.root_idx]
    save_motion_bvh(str(dst)+'.bvh', local, root, skeleton=skeleton, fps=model.fps)
    hierarchy = {
        'fps': float(model.fps),
        'joint_names': list(skeleton.bone_order_names),
        'joint_parents': [int(x) for x in skeleton.joint_parents.tolist()],
        'skeleton_name': skeleton.name,
        'coordinate_system': 'Y-up, meters, +Z forward initially',
    }
    (Path(str(dst)+'.skeleton.json')).write_text(json.dumps(hierarchy,indent=2)+'\n',encoding='utf8')
    return sample


def _metrics(sample, targets, diagnostics, model):
    pos=np.asarray(sample['posed_joints'])
    skel=model.skeleton
    if pos.shape[1] != skel.nbjoints:
        from kimodo.skeleton import SOMASkeleton30
        if isinstance(skel,SOMASkeleton30) and pos.shape[1] == skel.somaskel77.nbjoints:
            skel=skel.somaskel77
        else: raise ValueError('Output joint count differs from expected SOMA skeleton')
    inds=np.asarray(diagnostics['frame_indices'],dtype=int)
    pi=skel.bone_index['Hips']; wi=skel.bone_index['RightHand']; ti=skel.bone_index['RightHandMiddleEnd']
    wr=np.asarray(diagnostics['right_wrist_targets_m'])
    rt=np.asarray(diagnostics['soma_root_positions_m'])
    if len(pos)!=len(wr):
        raise ValueError(f'Expected {len(wr)} motion frames, received {len(pos)}')
    werr=np.linalg.norm(pos[:,wi]-wr,axis=1)
    rerr=np.linalg.norm(pos[:,pi]-rt,axis=1)
    rel_err=np.linalg.norm((pos[:,wi]-pos[:,pi])-(wr-rt),axis=1)
    metrics={
        'root_mean_m':float(np.mean(rerr)), 'root_max_m':float(np.max(rerr)),
        'wrist_mean_m_unconditioned_included':float(np.mean(werr)),
        'wrist_max_m_unconditioned_included':float(np.max(werr)),
        'wrist_keyframe_mean_m':float(np.mean(werr[inds])) if len(inds) else None,
        'wrist_keyframe_max_m':float(np.max(werr[inds])) if len(inds) else None,
        'pelvis_relative_wrist_keyframe_mean_m':float(np.mean(rel_err[inds])) if len(inds) else None,
        'root_keyframe_mean_m':float(np.mean(rerr[inds])) if len(inds) else None,
        'right_wrist_speed_max_mps':float(np.max(np.linalg.norm(np.diff(pos[:,wi],axis=0),axis=1))*model.fps),
        'right_hand_tip_speed_max_mps':float(np.max(np.linalg.norm(np.diff(pos[:,ti],axis=0),axis=1))*model.fps),
        'walking_frame_count': int(targets.get('phase_split_frame') or (len(pos) if not len(inds) else 0)),
        'right_hand_constraint_keyframes':int(len(inds)),
        'semantics':'Wrist keyframe metrics exclude unconstrained walking frames; no dynamic feasibility implied.',
    }
    return metrics


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--targets',required=True)
    p.add_argument('--reference',required=True,help='KiMoDo SOMA NPZ containing local_rot_mats and root_positions')
    p.add_argument('--out',required=True,help='Output stem (no extension)')
    p.add_argument('--model',default='Kimodo-SOMA-RP-v1.1')
    p.add_argument('--reference-frame',type=int,default=0)
    p.add_argument('--reference-yaw',type=float,default=0.0,help='Heading of reference clip in Y-up world, radians')
    p.add_argument('--tip-policy',choices=['calibrated','planned'],default='calibrated')
    p.add_argument('--diffusion-steps',type=int,default=100)
    p.add_argument('--seed',type=int,default=7)
    p.add_argument('--prompt',default='A person walks forward, stops, and extends the right hand for a handshake.')
    p.add_argument('--walk-prompt',default=None)
    p.add_argument('--reach-prompt',default=None)
    p.add_argument('--single-prompt',action='store_true',help='Disable automatic walking/reaching prompt split')
    p.add_argument('--num-transition-frames',type=int,default=8)
    p.add_argument('--check-only',action='store_true',help='Load SOMA skeleton and construct constraints; do not load diffusion checkpoint')
    args=p.parse_args()
    obj=_validate_target_file(args.targets)
    out=Path(args.out)
    out.parent.mkdir(parents=True,exist_ok=True)
    if args.check_only:
        from kimodo.skeleton import SOMASkeleton30
        skeleton=SOMASkeleton30()
        model=None
    else:
        from kimodo import load_model
        import torch
        device='cuda:0' if torch.cuda.is_available() else 'cpu'
        model=load_model(args.model,device=device,default_family='Kimodo')
        skeleton=model.skeleton
        if abs(float(model.fps)-float(obj['fps']))>1e-3:
            raise ValueError(f'MPC exported {obj["fps"]} fps but actual KiMoDo model uses {model.fps} fps. Re-run targets.py with actual FPS.')
    ref_pos, ref_rot, ref_root=reference_pose(args.reference,skeleton,args.reference_frame)
    constraints,diag=create_constraints(obj,skeleton,ref_pos,ref_rot,ref_root,
                                        args.reference_yaw,args.tip_policy)
    (out.parent/(out.name+'.constraint_diagnostics.json')).write_text(json.dumps(diag,indent=2)+'\n',encoding='utf8')
    print(f'Constructed {len(constraints)} in-memory constraint sets; '+
          f"reference→planner root height shift {diag['soma_root_height_shift_m']:.3f}m; "+
          f"max requested tip-vs-SOMA tip gap {diag['max_tip_discrepancy_m']}m")
    if args.check_only:
        print('CHECK ONLY: no KiMoDo diffusion inference or BVH/NPZ files were generated.')
        return
    output=_run_generation(model,constraints,obj,args.prompt,args.diffusion_steps,args.seed,
                           args.walk_prompt,args.reach_prompt,args.num_transition_frames,args.single_prompt)
    sample=_save_generation(output,model,str(out))
    metrics=_metrics(sample,obj,diag,model)
    (out.parent/(out.name+'.metrics.json')).write_text(json.dumps(metrics,indent=2)+'\n',encoding='utf8')
    print('Generated',str(out)+'.npz',str(out)+'.bvh')
    print('Generated wrist keyframe mean error (m):',metrics['wrist_keyframe_mean_m'])

if __name__=='__main__':
    main()
